/**
 * خواندن زبان انتخاب‌شده در server-side components (مثل dashboard/page.tsx).
 * LanguageProvider انتخاب را در cookie با کلید "site-lang" ذخیره می‌کند.
 * در صورت نبودن cookie، پیش‌فرض "en" برمی‌گردد.
 */
export async function getServerLang(): Promise<Lang> {
  try {
    const { cookies } = await import("next/headers");
    const jar = await cookies();
    const stored = jar.get("site-lang")?.value;
    if (stored === "fa" || stored === "en") return stored;
  } catch {
    /* در محیط‌های غیر-Next gracefully fail کن */
  }
  return "en";
}

/**
 * زبان برای Route Handlerها (API) — همان کوکی "site-lang" را می‌خواند.
 * getServerLang داخل Route Handler هم کار می‌کند؛ این اسم فقط پرده از
 * قصد فراخواننده برمی‌دارد (پیام‌های خطای API باید دوزبانه باشند).
 */
export async function getApiLang(): Promise<Lang> {
  return getServerLang();
}

/**
 * پیام کاربر-موجَه API به زبان درخواست — برای پاسخ‌های { error: "..." }.
 * FA متن اصلی را نگه می‌دارد؛ EN معادل حرفه‌ای.
 */
export async function apiMsg(fa: string, en: string): Promise<string> {
  return (await getApiLang()) === "fa" ? fa : en;
}

/** Convert Latin digits to Persian digits (used in the fa locale). */
const FA_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];
export function toFaDigits(value: string | number): string {
  return String(value).replace(/[0-9]/g, (d) => FA_DIGITS[Number(d)]);
}

/**
 * Label for a "'26"-style year string in the current locale.
 * English keeps the apostrophe style; Persian uses Persian digits.
 */
export function yearLabel(year: string, lang: Lang): string {
  if (lang !== "fa") return year;
  return toFaDigits(year.replace(/['’]/g, ""));
}

/** True when the string contains RTL (Arabic/Persian) script. */
export function hasRtlScript(text: string): boolean {
  return /[\u0590-\u08FF]/.test(text);
}
